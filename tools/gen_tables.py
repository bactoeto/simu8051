#!/usr/bin/env python3
"""Generate Python tables from isa.json and memory.json.

The generated modules contain only mechanical data: opcode metadata, SFR
addresses, reset values and interrupt/timer constants. Instruction semantics
live in core.py.
"""
from __future__ import annotations

import json
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ISA = ROOT / "data" / "isa.json"
MEM = ROOT / "data" / "memory.json"
ISA_TABLE = ROOT / "simu8051" / "isa_table.py"
MEM_TABLE = ROOT / "simu8051" / "mem_table.py"

HEADER = """# Generated by tools/gen_tables.py from {source}.
# Do not edit by hand; run `python3 tools/gen_tables.py`.
"""


def main() -> int:
    isa = json.loads(ISA.read_text(encoding="utf-8"))
    mem = json.loads(MEM.read_text(encoding="utf-8"))

    syntax_by_form = {inst["id"]: inst["syntax"] for inst in isa["instructions"]}
    opcodes: list[object] = [None] * 256
    for entry in isa["opcodes"]:
        op = int(entry["opcode"], 16)
        if entry.get("reserved"):
            opcodes[op] = None
        else:
            opcodes[op] = {
                "form": entry["form"],
                "bytes": entry["bytes"],
                "cycles": entry["cycles"],
                "syntax": syntax_by_form.get(entry["form"], entry["syntax"]),
            }
    forms = {
        inst["id"]: {
            "syntax": inst["syntax"],
            "bytes": inst["bytes"],
            "cycles": inst["cycles"],
            "flags": inst["flags"],
            "opcodes": inst["opcodes"],
            "registers": inst["registers"],
        }
        for inst in isa["instructions"]
    }

    isa_text = HEADER.format(source="data/isa.json")
    isa_text += "\nOPCODES = " + pprint.pformat(opcodes, width=100, sort_dicts=False) + "\n\n"
    isa_text += "FORMS = " + pprint.pformat(forms, width=100, sort_dicts=False) + "\n"
    ISA_TABLE.write_text(isa_text, encoding="utf-8")

    sfrs = {s["name"]: int(s["address"], 16) for s in mem["sfrs"]}
    sfrs_by_addr = {addr: name for name, addr in sfrs.items()}
    reset = {}
    for s in mem["sfrs"]:
        reset[int(s["address"], 16)] = s["reset"]
    bit_addressable = {
        int(s["address"], 16): s["name"] for s in mem["sfrs"] if s["bit_addressable"]
    }
    ports = {"P0": 0x80, "P1": 0x90, "P2": 0xA0, "P3": 0xB0}
    vectors = mem["spaces"]["program"]["vectors"]
    ie_bits = mem["interrupts"]["ie_bits"]
    ip_bits = mem["interrupts"]["ip_bits"]

    mem_text = HEADER.format(source="data/memory.json")
    mem_text += "\nSFR = " + pprint.pformat(sfrs, width=100, sort_dicts=False) + "\n\n"
    mem_text += "SFR_BY_ADDR = " + pprint.pformat(sfrs_by_addr, width=100, sort_dicts=False) + "\n\n"
    mem_text += "SFR_RESET = " + pprint.pformat(reset, width=100, sort_dicts=False) + "\n\n"
    mem_text += "BIT_ADDRESSABLE = " + pprint.pformat(bit_addressable, width=100, sort_dicts=False) + "\n\n"
    mem_text += "PORTS = " + pprint.pformat(ports, width=100, sort_dicts=False) + "\n\n"
    mem_text += "VECTORS = " + pprint.pformat(vectors, width=100, sort_dicts=False) + "\n\n"
    mem_text += "IE_BITS = " + pprint.pformat(ie_bits, width=100, sort_dicts=False) + "\n\n"
    mem_text += "IP_BITS = " + pprint.pformat(ip_bits, width=100, sort_dicts=False) + "\n"
    MEM_TABLE.write_text(mem_text, encoding="utf-8")

    print(f"wrote {ISA_TABLE}")
    print(f"wrote {MEM_TABLE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
